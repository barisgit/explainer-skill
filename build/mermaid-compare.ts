/**
 * Mermaid renderer comparison (not part of pack): draws every diagram in test/fixtures/mermaid-stress with this checkout's
 * renderer, optionally with another checkout's (`--base <dir>`, an explainer-skill checkout such as a worktree of an older
 * commit, drawn with its own stylesheet) and with official Mermaid in Chrome (`--official <file>`, an IIFE bundle that sets
 * `window.mermaid` with the ELK layouts registered), then writes one PNG per fixture with the drawings side by side, each at
 * its drawn size, plus one PNG per drawing (`<fixture>.<column>.png`).
 *
 *   bun build/mermaid-compare.ts [--base <dir>] [--official <bundle.js>] [--out <dir>] [--page] [name ...]
 *
 * `--page` also writes the fixtures' page.mdx (one section per fixture), the page `check` and the tests read.
 * Needs Chrome; hold /tmp/explainer-chrome.lock around it as around any other Chrome command.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import type { Cdp } from "../skills/explainer/src/cdp.ts";
import { withPage } from "../skills/explainer/src/chrome.ts";
import type { Diagram } from "../skills/explainer/src/mermaid.ts";
import { renderMermaid } from "../skills/explainer/src/mermaid.ts";
import { open } from "./media/page.ts";

const ROOT = resolve(import.meta.dir, "..");
const FIXTURES = join(ROOT, "test/fixtures/mermaid-stress");
const cliOf = (checkout: string) => join(checkout, "skills/explainer/cli.ts");

type Render = (source: string, n: number) => Diagram | Error;
interface Fixture {
	name: string;
	source: string;
}

function argValue(args: string[], flag: string): string | undefined {
	const at = args.indexOf(flag);
	return at < 0 ? undefined : args[at + 1];
}

function fixtures(only: string[]): Fixture[] {
	return readdirSync(FIXTURES)
		.filter((file) => file.endsWith(".mmd"))
		.sort()
		.map((file) => ({
			name: file.replace(/\.mmd$/, ""),
			source: readFileSync(join(FIXTURES, file), "utf8"),
		}))
		.filter(({ name }) => only.length === 0 || only.some((part) => name.includes(part)));
}

/** The fixtures as one page: a section per fixture, its first comment line as the section's text. */
function page(all: Fixture[]): string {
	const sections = all.map(({ name, source }) => {
		const note = /^%%\s*(.+)$/m.exec(source)?.[1] ?? "";
		const body = source.replace(/^%%.*\n/gm, "").trim();
		return `## ${name}\n\n${note ? `${note}\n\n` : ""}\`\`\`mermaid\n${body}\n\`\`\``;
	});
	return `---\ntitle: Mermaid stress fixtures\n---\n\n# Mermaid stress fixtures\n\nDiagrams that break naive layouts. Generated by build/mermaid-compare.ts --page from the .mmd files beside it.\n\n${sections.join("\n\n")}\n`;
}

/** The kit's stylesheets as a packed page from `checkout` carries them (fonts, tokens, the Mermaid rules). */
async function kitStyles(dir: string, checkout: string): Promise<string> {
	const mdx = join(dir, "styles.mdx");
	const out = join(dir, "styles.html");
	writeFileSync(mdx, "# Styles\n\n```mermaid\nflowchart LR\n  a --> b\n```\n");
	const pack = Bun.spawnSync(["bun", cliOf(checkout), "pack", mdx, "-o", out]);
	if (pack.exitCode !== 0) {
		throw new Error(`pack failed: ${pack.stderr.toString()}`);
	}
	return [...readFileSync(out, "utf8").matchAll(/<style\b[\s\S]*?<\/style>/g)]
		.map(([style]) => style)
		.join("\n");
}

const escapeHtml = (text: string) =>
	text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function drawn(render: Render, fixture: Fixture, n: number): string {
	const diagram = render(fixture.source, n);
	if (diagram instanceof Error) {
		return `<p class="error">${escapeHtml(diagram.message)}</p>`;
	}
	// The desktop copy at its drawn size, so columns compare like for like.
	const width = /viewBox="[\d.-]+ [\d.-]+ ([\d.]+)/.exec(diagram.svg)?.[1] ?? "";
	return `<div class="mermaid">${diagram.svg.replace('width="100%"', `width="${width}"`)}</div>`;
}

interface Column {
	label: string;
	cell: (fixture: Fixture, row: number) => string;
}

function columns(base: Render | undefined, official: boolean): Column[] {
	const kit = (label: string, render: Render, slot: number): Column => ({
		label,
		cell: (fixture, row) => drawn(render, fixture, row * 10 + slot),
	});
	const mermaid = (layout: string): Column => ({
		label: `official mermaid (${layout}, in Chrome)`,
		cell: ({ source }) =>
			`<div class="official" data-layout="${layout}">${escapeHtml(source.replace(/^%%.*\n/gm, ""))}</div>`,
	});
	return [
		...(base ? [kit("explainer before (--base)", base, 1)] : []),
		kit("explainer (this checkout)", renderMermaid, 2),
		...(official ? [mermaid("dagre"), mermaid("elk")] : []),
	];
}

const OFFICIAL_RUN = `
(async () => {
	const blocks = [...document.querySelectorAll(".official")];
	let n = 0;
	for (const block of blocks) {
		const layout = block.dataset.layout;
		mermaid.initialize({ startOnLoad: false, layout, theme: "neutral", themeVariables: { fontFamily: "Geist", fontSize: "13px" } });
		try {
			const { svg } = await mermaid.render("official" + n++, block.textContent);
			block.innerHTML = svg;
			const drawing = block.querySelector("svg");
			drawing.setAttribute("width", drawing.viewBox.baseVal.width);
			drawing.style.maxWidth = "none";
		} catch (error) {
			block.textContent = String(error);
		}
	}
	window.officialDone = true;
})();`;

function comparePage(styles: string, all: Fixture[], cols: Column[], official?: string): string {
	const rows = all.map(
		(fixture, row) =>
			`<section id="row-${row}"><h2>${fixture.name}</h2><div class="cols">${cols
				.map(
					(col) =>
						`<figure><figcaption>${col.label}</figcaption>${col.cell(fixture, row)}</figure>`,
				)
				.join("")}</div></section>`,
	);
	const script = official
		? `<script src="file://${official}"></script><script>${OFFICIAL_RUN}</script>`
		: "<script>window.officialDone = true</script>";
	return `<!doctype html><html lang="en"><head><meta charset="utf-8">${styles}<style>
body { margin: 0; padding: 16px; background: var(--under); color: var(--ink); font-family: var(--font); }
section { display: block; width: max-content; padding: 8px 16px 24px; }
h2 { font-size: 15px; margin: 0 0 8px; }
.cols { display: grid; grid-template-columns: repeat(2, max-content); gap: 24px 32px; align-items: start; }
figure { margin: 0; border-left: 1px solid var(--rule); padding-left: 16px; }
figcaption { font-size: 13px; color: var(--muted); }
.mermaid { margin: 0; text-align: left; overflow: visible; }
.mermaid > svg { max-width: none !important; min-width: 0; }
.mermaid > svg[data-phone] { display: none; }
.error { color: var(--bad); max-width: 30em; }
.official { white-space: pre; font-size: 11px; }
</style></head><body>${rows.join("")}${script}</body></html>`;
}

/** The page box of `selector` (document coordinates), whole pixels. */
async function pageBox(cdp: Cdp, selector: string) {
	return await cdp.evaluate<{ x: number; y: number; width: number; height: number }>(`(() => {
		const el = document.querySelector(${JSON.stringify(selector)});
		const r = el.getBoundingClientRect();
		return { x: Math.floor(r.x + scrollX), y: Math.floor(r.y + scrollY), width: Math.ceil(r.width), height: Math.ceil(r.height) };
	})()`);
}

/** A PNG of `selector`, wherever it is on the page (Chrome draws past the viewport for it). */
async function shoot(cdp: Cdp, selector: string, file: string) {
	const clip = { ...(await pageBox(cdp, selector)), scale: 1 };
	const { data } = await cdp.send<{ data: string }>("Page.captureScreenshot", {
		format: "png",
		clip,
		captureBeyondViewport: true,
	});
	writeFileSync(file, Buffer.from(data, "base64"));
}

async function capture(file: string, out: string, names: string[]) {
	await withPage(async (cdp) => {
		await open(cdp, `file://${file}`, { width: 2400, height: 1200 }, "light", true);
		for (
			let i = 0;
			i < 100 && !(await cdp.evaluate<boolean>("Boolean(window.officialDone)"));
			i++
		) {
			await Bun.sleep(100);
		}
		for (const [row, name] of names.entries()) {
			await shoot(cdp, `#row-${row}`, join(out, `${name}.png`));
			const cells = await cdp.evaluate<number>(
				`document.querySelectorAll("#row-${row} figure").length`,
			);
			for (let cell = 1; cell <= cells; cell++) {
				await shoot(cdp, `#row-${row} figure:nth-child(${cell})`, join(out, `${name}.${cell}.png`));
			}
		}
	});
}

async function main() {
	const args = Bun.argv.slice(2);
	const baseDir = argValue(args, "--base");
	const official = argValue(args, "--official");
	const out = resolve(argValue(args, "--out") ?? join(tmpdir(), "mermaid-compare"));
	const flags = new Set(["--base", "--official", "--out"]);
	const only = args.filter((arg, i) => !arg.startsWith("--") && !flags.has(args[i - 1] ?? ""));
	const all = fixtures(only);
	if (args.includes("--page")) {
		writeFileSync(join(FIXTURES, "page.mdx"), page(fixtures([])));
	}
	const base = baseDir
		? ((await import(resolve(baseDir, "skills/explainer/src/mermaid.ts"))).renderMermaid as Render)
		: undefined;
	mkdirSync(out, { recursive: true });
	const cols = columns(base, Boolean(official));
	const styles = baseDir ? [await kitStyles(out, resolve(baseDir))] : [];
	styles.push(await kitStyles(out, ROOT));
	const html = comparePage(styles.join("\n"), all, cols, official && resolve(official));
	const file = join(out, "compare.html");
	writeFileSync(file, html);
	await capture(
		file,
		out,
		all.map(({ name }) => name),
	);
	console.log(`${all.length} comparisons in ${out}`);
}

await main();
