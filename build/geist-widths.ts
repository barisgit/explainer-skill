#!/usr/bin/env bun
/**
 * Measures the kit's Geist in Chrome and writes the advance-width table into skills/explainer/src/geist.ts, between its
 * geist-widths markers: printable ASCII at the weights text is drawn in, in thousandths of an em, kerning left out. pack
 * measures chart and plot labels with it, and the beautiful-mermaid patch sizes diagram boxes with it. Geist Mono needs no
 * table: its 0.6 em advance is the diagram renderer's own monospace estimate.
 *
 * Rerun when kit/fonts changes: `bun build/geist-widths.ts`, `bun run format`, `bun run vendor`.
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { withPage } from "../skills/explainer/src/chrome.ts";

/** The weights text is drawn in: diagram edge labels and messages 400, node labels and plot labels 500, group headers 600. */
const WEIGHTS = [400, 500, 600];
const root = join(import.meta.dir, "..");
const fonts = join(root, "skills", "explainer", "kit", "fonts");
const target = join(root, "skills", "explainer", "src", "geist.ts");
const START = "// geist-widths:start";
const END = "// geist-widths:end";
const face = (family: string, file: string) =>
	`@font-face{font-family:"${family}";font-weight:100 900;src:url("${pathToFileURL(join(fonts, file))}")}`;

const dir = mkdtempSync(join(tmpdir(), "geist-widths-"));
const page = join(dir, "measure.html");
writeFileSync(page, `<!doctype html><style>${face("Geist", "geist.woff2")}</style>`);

const MEASURE = `(async () => {
	const weights = ${JSON.stringify(WEIGHTS)};
	await Promise.all(weights.map((w) => document.fonts.load(w + " 100px Geist")));
	const ctx = document.createElement("canvas").getContext("2d");
	const chars = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i));
	const em = (font, c) => { ctx.font = font; return Math.round(ctx.measureText(c).width * 10); };
	return {
		sans: Object.fromEntries(weights.map((w) => [w, chars.map((c) => em(w + " 100px Geist", c))])),
		loaded: [...document.fonts].some((f) => f.status === "loaded"),
	};
})()`;

try {
	const table = await withPage(async (cdp) => {
		await cdp.send("Runtime.enable");
		await cdp.send("Page.enable");
		await cdp.load(pathToFileURL(page).href);
		return cdp.evaluate<{ sans: Record<string, number[]>; loaded: boolean }>(MEASURE, true);
	});
	if (!table.loaded) {
		throw new Error(`Chrome did not load ${join(fonts, "geist.woff2")}`);
	}
	const rows = Object.entries(table.sans).map(
		([weight, widths]) => `  ${weight}: [${widths.join(", ")}],`,
	);
	const block = `${START}
// Generated by build/geist-widths.ts from the kit's Geist font; rerun it when the font changes.
/** Advance widths of printable ASCII (U+0020 to U+007E) in Geist, in thousandths of an em, by font weight. */
const GEIST_WIDTHS: Record<number, readonly number[]> = {
${rows.join("\n")}
}
${END}`;
	const source = readFileSync(target, "utf8");
	const [before, rest] = source.split(START);
	const after = rest?.split(END)[1];
	if (before === undefined || after === undefined) {
		throw new Error(`${target} has no ${START} ... ${END} block`);
	}
	writeFileSync(target, before + block + after);
	process.stdout.write(`wrote ${rows.length} weights to ${target}\n`);
} finally {
	rmSync(dir, { recursive: true, force: true });
}
